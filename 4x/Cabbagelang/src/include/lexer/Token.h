#ifndef LEXER_TOKEN_H
#define LEXER_TOKEN_H

#include <memory>

#include <utils/str_handle.h>
#include <log/log.h>

namespace lexer {

enum TokenKind {
    TOKEN_INT, TOKEN_CHAR, TOKEN_SHORT, TOKEN_LONG, TOKEN_FLOAT, TOKEN_DOUBLE, TOKEN_BOOL, TOKEN_BYTE, TOKEN_VOID,
    TOKEN_VOLATILE, TOKEN_CONST, TOKEN_STATIC, TOKEN_CAST, TOKEN_INLINE, TOKEN_TRUE, TOKEN_FALSE, TOKEN_NULL, TOKEN_BREAK, 
    TOKEN_CONTINUE, TOKEN_SWITCH, TOKEN_CASE, TOKEN_DEFAULT, TOKEN_LABEL, TOKEN_GOTO, 
    TOKEN_IMPORT, TOKEN_PACKAGE, TOKEN_QUOTE,
    TOKEN_IF, TOKEN_ELSE, TOKEN_WHILE, TOKEN_DO, TOKEN_FOR, TOKEN_RETURN, TOKEN_TRY, TOKEN_CATCH, TOKEN_THROW, TOKEN_FINALLY,
    TOKEN_CLASS, TOKEN_NEW, TOKEN_PRIVATE, TOKEN_PROTECTED, TOKEN_SHARED, TOKEN_PUBLIC, TOKEN_SELF, TOKEN_SUPER, TOKEN_OPERATOR,
    TOKEN_ADD, TOKEN_SUB, TOKEN_MUL, TOKEN_DIV, TOKEN_MOD,
    TOKEN_INC, TOKEN_DEC, TOKEN_EQ, TOKEN_NEQ, 
    TOKEN_GT, TOKEN_LT, TOKEN_GTE, TOKEN_LTE, 
    TOKEN_AND, TOKEN_OR, TOKEN_NOT, 
    TOKEN_BIT_AND, TOKEN_BIT_OR, TOKEN_BIT_XOR, 
    TOKEN_BIT_NOT, TOKEN_SHIFT_LEFT, TOKEN_SHIFT_RIGHT, 
    TOKEN_ASSIGN, TOKEN_ADD_ASSIGN, TOKEN_SUB_ASSIGN, 
    TOKEN_MUL_ASSIGN, TOKEN_DIV_ASSIGN, TOKEN_MOD_ASSIGN, 
    TOKEN_SHIFT_LEFT_ASSIGN, TOKEN_SHIFT_RIGHT_ASSIGN, 
    TOKEN_BIT_AND_ASSIGN, TOKEN_BIT_XOR_ASSIGN, TOKEN_BIT_OR_ASSIGN, TOKEN_BIT_NOT_ASSIGN,
    TOKEN_LPAREN, TOKEN_RPAREN, TOKEN_LBRACKET, TOKEN_RBRACKET,
    TOKEN_LBRACE, TOKEN_RBRACE, TOKEN_COMMA, TOKEN_DOT, TOKEN_ELLIPSIS, TOKEN_QUESTION,
    TOKEN_SEMICOLON, TOKEN_COLON,
    TOKEN_IDENTIFIER, TOKEN_INT_LITERAL, TOKEN_CHAR_LITERAL, TOKEN_FLOAT_LITERAL, TOKEN_STRING_LITERAL
};

struct Token {
    TokenKind kind;
    std::string data;
    int line, column;

    Token(TokenKind kind, const std::string &data, int line, int column) :
        kind(kind), data(data), line(line), column(column) {}
};

using aToken = Token*;

aToken create_token(TokenKind kind, const std::string &data, int line, int column);

} // namespace lexer

#endif // LEXER_TOKEN_H